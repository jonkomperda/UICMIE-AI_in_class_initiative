    function onUndoPoint(~, ~)
        if isempty(state.profilePoints)
            setStatus("nothing to undo");
            logMessage("Undo ignored because no ambient profile points are available.");
            return;
        end

        state.profilePoints(end, :) = [];
        state.profileSource = 'manual';
        state.currentProfileName = 'Custom';
        state.lastResults = [];
        refreshAmbientPlot();
        refreshResultsPlot();
        updateMetricsBox();

        if isempty(state.profilePoints)
            setStatus("profile cleared");
            logMessage("Removed the last point. No ambient profile points remain.");
        else
            setStatus("removed last point");
            logMessage("Removed the most recently stored ambient profile point.");
        end
    end

    function onClearProfile(~, ~)
        state.profilePoints = zeros(0, 2);
        state.profileSource = 'manual';
        state.currentProfileName = 'Custom';
        state.lastResults = [];
        refreshAmbientPlot();
        refreshResultsPlot();
        updateMetricsBox();
        setStatus("profile cleared");
        logMessage("Cleared the ambient profile and previous simulation results.");
    end

    function onRunSimulation(~, ~)
        try
            params = readAppParameters(true, true);
            ambientProfile = buildAmbientProfile();
            results = simulateControllers(ambientProfile, params);
        catch exception
            setStatus("simulation blocked");
            logMessage(exception.message);
            return;
        end

        state.lastResults = results;
        refreshResultsPlot();
        updateMetricsBox();
        refreshNnPanel();

        setStatus("simulation complete");
        try
            summaryMessage = buildSimulationSummary(results);
        catch
            summaryMessage = sprintf('Simulation complete for %s.', char(results.profileName));
        end
        logMessage(summaryMessage);
    end

    function onTrainNn(~, ~)
        try
            setStatus("training nn");
            drawnow;

            params = readAppParameters(false, false);
            trainingSettings = readNnTrainingSettings();
            featureFlags = readNnFeatureFlagsFromUi();
            trainingProfiles = getTrainingProfiles();
            [trainingInputs, trainingTargets] = buildNnTrainingDataset(trainingProfiles, params, featureFlags);
            state.nnModel = trainNeuralNetwork(trainingInputs, trainingTargets, featureFlags, trainingSettings);

            refreshNnPanel();
            setStatus("nn trained");
            logMessage(sprintf( ...
                "NN training complete. Final loss %.5f using %s.", ...
                state.nnModel.loss, char(state.nnModel.featureSummary)));
        catch exception
            refreshNnPanel();
            setStatus("nn training blocked");
            logMessage(exception.message);
        end
    end

    function onFigureClick(~, ~)
        if ~state.isSelecting || ~ishandle(state.fig)
            return;
        end

        clickedObject = hittest(state.fig);
        clickedAxes = ancestor(clickedObject, "axes");
        if isempty(clickedAxes) || clickedAxes ~= state.ambientAxes
            return;
        end

        currentPoint = get(state.ambientAxes, "CurrentPoint");
        xPoint = currentPoint(1, 1);
        yPoint = currentPoint(1, 2);
        xLimits = get(state.ambientAxes, "XLim");
        yLimits = get(state.ambientAxes, "YLim");

        if xPoint < xLimits(1) || xPoint > xLimits(2) || yPoint < yLimits(1) || yPoint > yLimits(2)
